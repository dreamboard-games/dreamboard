function resolveEffectiveBaseSetup(options: {
  manifest: GameTopologyManifest;
  base: TypedBaseDefinition;
  basesById?: Map<string, LoadedBase>;
}): EffectiveBaseSetup {
  const inheritedSetupProfileId =
    options.base.setupProfileId ??
    (options.base.extends && options.basesById
      ? resolveEffectiveBaseSetup({
          manifest: options.manifest,
          base:
            options.basesById.get(options.base.extends)?.definition ??
            (() => {
              throw new Error(
                `Base '${options.base.id}' extends unknown parent '${options.base.extends}'.`,
              );
            })(),
          basesById: options.basesById,
        }).setupProfileId
      : undefined);
  const selection = resolveSetupProfileSelection({
    manifest: options.manifest,
    requestedSetupProfileId: inheritedSetupProfileId ?? undefined,
  });
  return {
    setupProfileId: selection.id,
  };
}

function resolveBaseDefinition(
  base: LoadedBase,
  basesById: Map<string, LoadedBase>,
): ResolvedBaseDefinition {
  const inherited =
    base.definition.extends !== undefined
      ? resolveBaseDefinition(
          basesById.get(base.definition.extends) ??
            (() => {
              throw new Error(
                `Base '${base.definition.id}' extends unknown parent '${base.definition.extends}'.`,
              );
            })(),
          basesById,
        )
      : null;

  const seed = base.definition.seed ?? inherited?.seed;
  const players = base.definition.players ?? inherited?.players;
  if (seed === undefined || players === undefined) {
    throw new Error(
      `Base '${base.definition.id}' must resolve numeric seed and players.`,
    );
  }

  return {
    ...base.definition,
    seed,
    players,
    setupProfileId:
      base.definition.setupProfileId ?? inherited?.setupProfileId ?? undefined,
  };
}

function summarizeTableValidationError(
  manifest: GameTopologyManifest,
  error: Error,
): string {
  const issues = error.message
    .split("; ")
    .map((issue) => issue.trim())
    .filter((issue) => issue.length > 0);

  if (
    issues.length === 0 ||
    !issues.every((issue) => issue.startsWith("table"))
  ) {
    return error.message;
  }

  const boardBaseIdByRuntimeId = new Map<string, string>(
    (manifest.boards ?? []).flatMap((board: BoardSpec) =>
      board.scope === "perPlayer"
        ? Array.from(
            { length: manifest.players.maxPlayers },
            (_, index) =>
              [`${board.id}:player-${index + 1}`, board.id] as const,
          )
        : ([[board.id, board.id]] as const),
    ),
  );

  const representativeIssues = issues.slice(0, 3).map((issue) => {
    const [, runtimeBoardId = ""] =
      issue.match(/^table\.boards\.byId\.([^.]+)\./) ?? [];
    const boardBaseId = boardBaseIdByRuntimeId.get(runtimeBoardId);
    if (!boardBaseId) {
      return `- ${issue.replace(/^table\./, "")}`;
    }
    const boardSpecificPath = issue
      .replace(/^table\.boards\.byId\.[^.]+\./, "")
      .replace(/^table\./, "");
    return `- board '${boardBaseId}' (${runtimeBoardId}): ${boardSpecificPath}`;
  });

  return [
    `Reducer-native table validation failed with ${issues.length} issue${issues.length === 1 ? "" : "s"}.`,
    "Likely root cause: the generated test table shape does not match the authored manifest topology.",
    ...representativeIssues,
    "Pass --debug for the full validation dump.",
  ].join("\n");
}

class ShadowReducerRuntime {
  private readonly bundle: ReturnType<typeof createReducerBundle>;
  private readonly runtime: ReturnType<
    ReturnType<typeof createReducerBundle>["createInProcessRuntime"]
  >;
  private readonly playerIds: string[];
  private readonly historyRecords: HistoryRecord[] = [];
  private version = 0;
  private started = false;

  constructor(
    private readonly manifest: GameTopologyManifest,
    private readonly gameModuleDefault: unknown,
    private readonly createInitialTable: GeneratedInitialTableFactory | null,
    private readonly seed: number,
    private readonly players: number,
    private readonly setupProfileId: string | null,
    private readonly debug = false,
  ) {
    if (
      typeof gameModuleDefault !== "object" ||
      gameModuleDefault === null ||
      !("contract" in gameModuleDefault)
    ) {
      throw new Error(
        "app/game.ts must export a reducer-native game definition.",
      );
    }
    this.bundle = createReducerBundle(gameModuleDefault as never);
    this.runtime = this.bundle.createInProcessRuntime();
    this.playerIds = Array.from(
      { length: players },
      (_, index) => `player-${index + 1}`,
    );
  }

  async start(): Promise<void> {
    if (this.started) {
      return;
    }
    const random = new KotlinSeededRandom(this.seed);
    const shuffleItems = <Value>(values: readonly Value[]) =>
      shuffleWithKotlinRandom(values, random);
    // JSON-roundtrip the materialized table to mirror the backend wire
    // boundary: real flows serialize the table over HTTP, which drops
    // explicit `undefined` property values (e.g. optional card text) that
    // the bundle's strict JSON state schema would otherwise reject.
    const table: unknown = JSON.parse(
      JSON.stringify(
        this.createInitialTable?.({
          playerIds: this.playerIds,
          shuffleItems,
        }) ??
          materializeManifestTable({
            manifest: this.manifest,
            playerIds: this.playerIds,
            shuffleItems,
          }),
      ),
    );
    const rngSeed = random.nextReducerRuntimeSeed();
    try {
      await this.runtime.initialize({
        table: table as never,
        playerIds: this.playerIds,
        rngSeed,
        setup: this.setupProfileId
          ? {
              profileId: this.setupProfileId,
            }
          : null,
      });
    } catch (error) {
      if (!this.debug && error instanceof Error) {
        throw new Error(summarizeTableValidationError(this.manifest, error));
      }
      throw error;
    }
    this.version = 0;
    this.started = true;
  }

  phase(): string {
    return (
      ((
        (
          (this.runtime.unsafeState() as { domain?: unknown } | null)
            ?.domain as { flow?: { currentPhase?: string } } | undefined
        )?.flow as { currentPhase?: string } | undefined
      )?.currentPhase ??
        null) ||
      ""
    );
  }

  playerOrder(): string[] {
    return this.playerIds;
  }

  rawState(): Record<string, unknown> {
    return this.runtime.snapshot() as Record<string, unknown>;
  }

  currentVersion(): number {
    return this.version;
  }

  hydrate(snapshot: Record<string, unknown>, version = 0): void {
    this.runtime.hydrate({ state: structuredClone(snapshot) });
    this.version = version;
    this.started = true;
  }

  patchState(mutator: (state: Record<string, unknown>) => void): void {
    const next = structuredClone(this.rawState());
    mutator(next);
    this.hydrate(next, this.version + 1);
  }

  projectAllSeats(): {
    currentStage: string | null;
    stageSeats: string[];
    seats: Record<
      string,
      {
        view?: unknown;
        availableInteractions?: Array<Record<string, unknown>>;
        zones?: Record<string, unknown>;
      }
    >;
  } {
    type RawSeatProjection = {
      view?: unknown;
      availableInteractions?: Array<Record<string, unknown>>;
      availableInteractionRefs?: unknown;
      zones?: Record<string, unknown>;
    };
    type RawSeatProjectionBundle = {
      currentStage?: string | null;
      stageSeats?: string[];
      interactionsByRef?: unknown;
      seats?: Record<string, RawSeatProjection>;
    };

    const projection = this.runtime.projectSeatsDynamic({
      playerIds: this.playerIds as never,
    }) as RawSeatProjectionBundle;
    const interactionsByRef =
      projection.interactionsByRef &&
      typeof projection.interactionsByRef === "object" &&
      !Array.isArray(projection.interactionsByRef)
        ? (projection.interactionsByRef as Record<
            string,
            Record<string, unknown> | undefined
          >)
        : {};
    const seats = Object.fromEntries(
      Object.entries(projection.seats ?? {}).map(([playerId, seat]) => {
        const availableInteractionRefs = Array.isArray(
          seat.availableInteractionRefs,
        )
          ? seat.availableInteractionRefs.filter(
              (ref): ref is string => typeof ref === "string",
            )
          : [];
        const availableInteractions =
          seat.availableInteractions ??
          availableInteractionRefs
            .map((ref) => interactionsByRef[ref])
            .filter(
              (descriptor): descriptor is Record<string, unknown> =>
                !!descriptor && typeof descriptor === "object",
            );
        return [
          playerId,
          {
            view: seat.view,
            availableInteractions,
            zones: seat.zones,
          },
        ];
      }),
    );
    return {
      currentStage: projection.currentStage ?? null,
      stageSeats: projection.stageSeats ?? [],
      seats,
    };
  }

  currentStage(): string | null {
    return this.projectAllSeats().currentStage;
  }

  view(playerId: string): unknown {
    return (
      this.runtime.projectSeatViewDynamic({
        playerId: playerId as never,
      }) ?? null
    );
  }

  availableInteractionsForPlayer(playerId: string): string[] {
    const projection = this.projectAllSeats();
    const seat = projection.seats[playerId];
    const descriptors = seat?.availableInteractions ?? [];
    return descriptors
      .filter(
        (descriptor) =>
          !!descriptor && typeof descriptor.interactionId === "string",
      )
      .map((descriptor) => descriptor.interactionId as string);
  }

  /**
   * Phase-kind interaction descriptors (action + prompt) available to
   * `playerId` in the current phase. Surfaces the same projection the UI
   * SDK consumes, so scenarios can assert addressee authorization and
   * availability without reaching into game-specific state. Returned as
   * loose records — the typed `InteractionDescriptor` shape is narrowed
   * downstream in the workspace-generated `testing-contract.ts`.
   */
  interactionsForPlayer(playerId: string): Array<Record<string, unknown>> {
    return this.projectAllSeats().seats[playerId]?.availableInteractions ?? [];
  }

  explain(playerId: string, interactionId: string): unknown {
    const runtime = this.runtime as {
      explainInteraction?: (input: {
        playerId: string;
        interactionId: string;
      }) => unknown;
    };
    if (typeof runtime.explainInteraction !== "function") {
      throw new Error(
        "The installed @dreamboard-games/sdk does not expose interaction explanations. Update the workspace SDK pin.",
      );
    }
    return runtime.explainInteraction({ playerId, interactionId });
  }

  clearHistory(): void {
    this.historyRecords.length = 0;
  }

  private async applyInput(input: HistoryInput): Promise<void> {
    const parsedInput = toReducerInput(input);
    const result = await this.runtime.dispatch({ input: parsedInput });

    if (result.kind === "reject") {
      const record = {
        input,
        accepted: false,
        errorCode: result.errorCode,
        message: result.message,
      };
      this.historyRecords.push(record);
      throw createSubmissionError(
        result.errorCode,
        result.message,
        "Reducer input rejected.",
      );
    }

    this.version += 1;
    this.historyRecords.push({ input, accepted: true });
  }

  async submitInteraction(
    playerId: string,
    interactionId: string,
    params: Record<string, unknown>,
  ): Promise<void> {
    await this.applyInput({
      kind: "interaction",
      playerId,
      interactionId,
      params,
    });
  }
}

/**
 * Translate the harness's history record into the unified `interaction`
 * wire shape the ingress bundle accepts.
 */
function toReducerInput(input: HistoryInput): Record<string, unknown> {
  return {
    kind: "interaction",
    playerId: input.playerId,
    interactionId: input.interactionId,
    params: input.params,
  };
}

/**
 * Tracks live gameplay state for the remote runner. Gameplay event streams
 * live in the Gameplay Authority service, so the backend bootstrap snapshot
 * is fetched over REST; post-submit state follows the reducer shadow.
 */
class RemoteGameplayTracker {
  private readonly state: GameplaySnapshot = {
    version: -1,
    actionSetVersion: "",
    currentPhase: null,
    playerId: "player-1",
    view: null,
    availableInteractions: [],
  };
  private liveBootstrap = false;

  constructor(
    private readonly sessionId: string,
    private readonly playerId: string,
  ) {
    this.state.playerId = playerId;
  }

  async bootstrap(): Promise<void> {
    const { data, error, response } = await getSessionSnapshot({
      path: { sessionId: this.sessionId },
      query: { playerId: this.playerId },
    });
    if (error || !data || data.type !== "gameplay") {
      throw toDreamboardApiError(
        error ?? { detail: "Gameplay snapshot was unavailable." },
        response,
        "Failed to load the remote gameplay bootstrap snapshot",
      );
    }
    // "authority" is the backend sentinel for gameplay state owned by the
    // Gameplay Authority service. The snapshot still attests the session
    // reached gameplay against the real compiled result, but concrete state
    // assertions must follow the reducer shadow instead.
    if (data.gameplay.actionSetVersion === "authority") {
      return;
    }
    this.liveBootstrap = true;
    this.applyGameplay(data.gameplay);
  }

  hasLiveBootstrap(): boolean {
    return this.liveBootstrap;
  }

  snapshot(): GameplaySnapshot {
    return {
      ...this.state,
      availableInteractions: [...this.state.availableInteractions],
    };
  }

  applyShadow(shadow: ShadowReducerRuntime): void {
    const projection = shadow.projectAllSeats();
    const playerId = this.playerId;
    const seat = projection.seats[playerId];
    this.state.version = shadow.currentVersion();
    this.state.actionSetVersion = "";
    this.state.playerId = playerId;
    this.state.currentPhase = shadow.phase();
    this.state.view = seat?.view ?? null;
    this.state.availableInteractions =
      shadow.availableInteractionsForPlayer(playerId);
  }

  private applyGameplay(gameplay: HostPlayerGameplayView): void {
    const playerId = gameplay.perspectivePlayerId;
    const seat = gameplay.seats[playerId];
    this.state.version = gameplay.version;
    this.state.actionSetVersion = gameplay.actionSetVersion;
    this.state.playerId = playerId;
    this.state.currentPhase = gameplay.shared.currentPhase;
    this.state.view = parseSeatView(seat?.view ?? "null");
    this.state.availableInteractions = (seat?.availableInteractionRefs ?? [])
      .map((ref) => gameplay.interactionsByRef[ref])
      .filter((interaction): interaction is NonNullable<typeof interaction> =>
        Boolean(interaction),
      )
      .map((interaction) => interaction.interactionId);
  }
}

